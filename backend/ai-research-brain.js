export function classifyQuestion(message = '') {
  const text = String(message).trim();
  const rules = [
    ['continuation', /আগের গবেষণা|যেখানে থেমেছিল|চালিয়ে|আবার শুরু|continue/i],
    ['tool_command', /টুল|খুলে দাও|চালাও|ব্যবহার করো|তৈরি করো/],
    ['ayah_research', /আয়াত|আয়াত|সূরা|সুরা/],
    ['word_research', /শব্দ|শব্দের|token|লেমা|lemma/],
    ['root', /মূল ধাতু|রুট|root|ধাতু/],
    ['morphology', /সর্ফ|morphology|শব্দরূপ|রূপতত্ত্ব/],
    ['grammar', /ব্যাকরণ|ব্যাকরণগত|নাহু|ই‘রাব|ইরাব/],
    ['concordance', /concordance|সব ব্যবহার|কোথায় কোথায়|occurrence/],
    ['translation', /অনুবাদ|তরজমা|আক্ষরিক অর্থ|বাংলা অর্থ/],
    ['evidence', /প্রমাণ|উৎস|source|evidence|যাচাই/],
    ['math', /কতটি|কতবার|শতাংশ|গণনা|হিসাব|সংখ্যা/]
  ];
  for (const [type, pattern] of rules) if (pattern.test(text)) return type;
  return 'general';
}

